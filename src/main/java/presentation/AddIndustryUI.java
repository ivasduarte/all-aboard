package presentation;

import controller.AddIndustryController;
import controller.CreateScenarioController;
import controller.DisplayMapController;
import domain.*;
import repositories.MapRepository;
import repositories.Repositories;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.Scanner;

/**
 * The AddIndustryUI class provides a user-facing interface for adding a new industry
 * on an existing map. It implements the Runnable interface to enable execution
 * within a sequential or parallel execution context.
 */
public class AddIndustryUI implements Runnable {
    private AddIndustryController ctrl = new AddIndustryController();

    private Map map;
    private int mapID;
    private int positionX;
    private int positionY;
    private Industry.IndustryInfo industryType;
    private int cargoAmount;

    public AddIndustryUI(Map map) {
        MapRepository mapRepo = Repositories.getInstance().getMapRepository();
        this.map = map;
        this.mapID = mapRepo.getMapList().indexOf(map);
    }

    /**
     * This method will be responsible to show the UI to user.
     * This method will also collect all the inputs related to the industry and pass them to the controller.
     * <p>
     * Upon successful execution, a new industry is created, added to the selected
     * map, and reported to the user. If errors occur during the input process,
     * appropriate error messages are displayed to guide the user.
     */
    public boolean getInput() {
        Scanner sc = new Scanner(System.in);

        do {
            System.out.print("\nINDUSTRY'S X POSITION: ");
            positionX = sc.nextInt();

            if (positionX < 0 || positionX > map.getWidth()) {
                System.out.println("Invalid X coordinate!");
            }
        } while (positionX < 0 || positionX > map.getWidth());

        do {
            System.out.print("INDUSTRY'S Y POSITION: ");
            positionY = sc.nextInt();

            if (positionY < 0 || positionY > map.getHeight()) {
                System.out.println("Invalid Y coordinate!");
            }
        } while (positionY < 0 || positionY > map.getWidth());

        System.out.println();

        List<Industry> mapIndustries = map.getIndustries();
        List<City> mapCities = map.getCities();

        for (int i = 0; i < mapIndustries.size(); i++) {
            if (mapIndustries.get(i).getPositionX() == positionX && mapIndustries.get(i).getPositionY() == positionY) {
                System.out.println("Position is already occupied.");
                return false;
            }
        }

        for (int i = 0; i < mapCities.size(); i++) {
            for (int j = 0; j < mapCities.get(i).getBlocks().size(); j++) {
                List<HouseBlock> hb = mapCities.get(i).getBlocks();

                if (hb.get(j).getX() == positionX && hb.get(j).getY() == positionY) {
                    System.out.println("Position is already occupied.");
                    return false;
                }
            }
        }

        int industryTypeAnswer;
        do {
            for (int i = 0; i < Industry.IndustryInfo.values().length; i++) {
                System.out.println((i+1) + ". " + Industry.IndustryInfo.values()[i]);
            }
            System.out.print("SELECT THE PREFERRED INDUSTRY TYPE: ");
            industryTypeAnswer = sc.nextInt() - 1;

            if (industryTypeAnswer < 0 || industryTypeAnswer >= Industry.IndustryInfo.values().length) {
                System.out.println("Invalid option!");
            }
        } while (industryTypeAnswer < 0 || industryTypeAnswer >= Industry.IndustryInfo.values().length);
        industryType = Industry.IndustryInfo.values()[industryTypeAnswer];

        do {
            System.out.print("\nAMOUNT OF CARGO GENERATED BY THIS INDUSTRY IN A YEAR SPAN: ");
            cargoAmount = sc.nextInt();

            if (cargoAmount <= 0) {
                System.out.println("ERROR: Cargo amount must be a positive value.");
            }
        } while (cargoAmount <= 0);

        return true;
    }

    @Override
    /**
     * This method will be responsible to show the UI related to adding an industry to the editor when this action is selected.
     */
    public void run() {
        System.out.println("\n\n------------------------ Add Industry ------------------------");
        if (getInput()) {
            String result = ctrl.addIndustry(mapID, positionX, positionY, industryType, cargoAmount);
            System.out.println(result);
        } else {
            System.out.println("It is not possible to create this industry!");
        }
    }
}
