package presentation;

import controller.AddIndustryController;
import controller.CreateScenarioController;
import controller.DisplayMapController;
import domain.Map;
import domain.Scenario;
import repositories.MapRepository;
import repositories.Repositories;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.Scanner;

/**
 * The AddIndustryUI class provides a user-facing interface for adding a new industry
 * on an existing map. It implements the Runnable interface to enable execution
 * within a sequential or parallel execution context.
 */
public class AddIndustryUI implements Runnable {
    private AddIndustryController ctrl = new AddIndustryController();
    private DisplayMapController controller = new DisplayMapController();
    private CreateScenarioController scenarioController = new CreateScenarioController();

    private Map map;
    private int mapID;
    private int scenarioID;
    private int positionX;
    private int positionY;
    private String industryType;
    private int cargoAmount;
    private int cargoPrice;

    public AddIndustryUI(Map map) {
        MapRepository mapRepo = Repositories.getInstance().getMapRepository();
        this.map = map;
        this.mapID = mapRepo.getMapList().indexOf(map);
    }

    /**
     * This method will be responsible to show the UI to user.
     * This method will also collect all the inputs related to the industry and pass them to the controller.
     *
     * Upon successful execution, a new industry is created, added to the selected
     * map, and reported to the user. If errors occur during the input process,
     * appropriate error messages are displayed to guide the user.
     */
    public void getInput() {
        Scanner sc = new Scanner(System.in);

        MapRepository mapRepository = Repositories.getInstance().getMapRepository();
        Map map = mapRepository.getMapList().get(mapID);
        List<Scenario> scenarioList = scenarioController.getScenarioListByMap(map);

        for (int i = 0; i < scenarioList.size(); i++) {
            Scenario scenario = scenarioList.get(i);
            System.out.println((i+1) + ". " + scenario.getScenarioName());
        }
        System.out.println("Enter the scenario ID: ");
        scenarioID = sc.nextInt() - 1;

        System.out.println("\nEnter the position X of the industry: ");
        positionX = sc.nextInt();
        System.out.println("Enter the position Y of the industry: ");
        positionY = sc.nextInt();

        System.out.println();

        List<String> industryTypes = new ArrayList<>();
        industryTypes.add("Primary sector industry");
        industryTypes.add("Transforming industry");
        industryTypes.add("Mixed industry");
        for (int i = 0; i < industryTypes.size(); i++) {
            System.out.println((i+1) + ". " + industryTypes.get(i));
        }
        System.out.println("Select the industry type you want: ");
        int answer = sc.nextInt() - 1;
        industryType = industryTypes.get(answer);

        do {
            System.out.println("\nEnter the amount of cargo generated by the industry in 1 year: ");
            cargoAmount = sc.nextInt();

            if(cargoAmount <= 0)
            {
                System.out.println("Cargo amount must be a positive value!");
            }
        }while (cargoAmount <= 0);

        do {
            System.out.println("\nEnter the amount of money that each cargo gives to the player: ");
            cargoPrice = sc.nextInt();

            if(cargoPrice <= 0)
            {
                System.out.println("Each cargo must give positive money to the player!");
            }
        }while (cargoPrice <= 0);
    }

    @Override
    /**
     * This method will be responsible to show the UI related to adding an industry to the editor when this action is selected.
     */
    public void run() {
        System.out.println("\n\n------------------------ Add Industry ------------------------");
        getInput();
        submitData();
    }

    /**
     * This method will be responsible to show the success or error message to the Editor.
     */
    private void submitData() {
        Optional<String> result = Optional.ofNullable(ctrl.addIndustry(mapID, scenarioID, positionX, positionY, industryType, cargoAmount, cargoPrice));

        if (result.isPresent()) {
            System.out.println("\nIndustry successfully added!");
        } else {
            System.out.println("\nIndustry not added!");
        }
    }

    /**
     * This method will be responsible to show an error message if the industry cannot be created.
     *
     * @param result error message
     */
    public void showError(String result) {
        System.out.println("ERROR: " + result);
    }

    /**
     * This method will be responsible to show a message of success, if the industry is added.
     *
     * @param result success message
     */
    public void showSuccess(String result) {
        System.out.println("SUCCESS: " + result);
    }
}
