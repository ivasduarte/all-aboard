package controller;

import domain.Industry;
import domain.Map;
import repositories.IndustryRepository;
import repositories.Repositories;

/**
 * Controller class responsible for managing the creation and addition of new industries
 * to the system. This class handles the business logic for industry creation and
 * coordinates with the repository layer to persist the data.
 */
public class AddIndustryController {
    private IndustryRepository industryRepository;

    /**
     * Creates a new industry and adds it to the system.
     * This method handles the following steps:
     * 1. Creates a new Industry instance with the provided parameters
     * 2. Saves the industry to the repository
     * 3. Adds the industry to the specified map
     * 4. Returns a success message with industry details
     *
     * @param mapID ID of the map where the industry will be added
     * @param positionX X coordinate of the industry's position
     * @param positionY Y coordinate of the industry's position
     * @param industryType Type of industry to be created
     * @param cargoAmount Amount of cargo generated by the industry per year
     * @return A success message containing the industry details if creation is successful,
     *         or an error message if the operation fails
     */
    public String addIndustry(int mapID, int positionX, int positionY, Industry.IndustryInfo industryType, int cargoAmount) {
        IndustryRepository industryRepository = Repositories.getInstance().getIndustryRepository();

        Industry industry = new Industry(mapID, positionX, positionY, industryType, cargoAmount);

        industryRepository.save(industry);
        Map map = Repositories.getInstance().getMapRepository().getMapList().get(mapID);

        map.addNewIndustry(industry);

        return "\n"+ industryType.getName() + " added successfully at (" + positionX + ", " + positionY + ").\nIndustry Type: " + industryType.getType().getName();
    }

    /**
     * Retrieves the industry repository instance.
     * If the repository hasn't been initialized, it gets a new instance
     * from the Repositories singleton.
     *
     * @return The IndustryRepository instance
     */
    public IndustryRepository getIndustryRepository() {
        if (industryRepository == null) {
            Repositories repositories = Repositories.getInstance();
            industryRepository = repositories.getIndustryRepository();
        }
        return industryRepository;
    }
}
